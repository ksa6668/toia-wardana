// Batch 94: توحيد الأرقام إلى اللاتينية (0-9) على مستوى التطبيق.
//
// لوحة المفاتيح العربية على iOS تُدخل أرقاماً عربية-هندية (٠١٢…) أو
// فارسية (۰۱۲…) فتفشل المطابقة أو تُحذف صامتة (حقول PIN كانت تنقّي
// بـ replace(/\D/g,'') الذي يحذف الرقم الهندي بدل تحويله).
//
// تُطبَّق عند الكتابة (onChange) على الحقول الرقمية وحقول البحث فقط —
// النصوص الحرة (الأسماء، الأسباب، قوالب الرسائل) مستثناة عمداً: قد
// يقصد المدير كتابة أرقام عربية في نص تحريري.
//
// ملاحظة: normalizePhone في loyaltyMath.js محصّنة أصلاً عبر
// toEnglishDigits الداخلية — هذه الدالة مستقلة عنها بعقد مختلف:
// غير النص يُعاد كما هو بلا إجبار إلى String.
// ====================================================================

const ARABIC_INDIC = '٠١٢٣٤٥٦٧٨٩';   // U+0660–U+0669
const PERSIAN = '۰۱۲۳۴۵۶۷۸۹';        // U+06F0–U+06F9

/** تحويل أي أرقام عربية-هندية أو فارسية في النص إلى 0-9. غير النص يُعاد كما هو. */
export function toLatinDigits(value) {
  if (typeof value !== 'string') return value;
  return value.replace(/[٠-٩۰-۹]/g, (ch) => {
    const a = ARABIC_INDIC.indexOf(ch);
    if (a >= 0) return String(a);
    const p = PERSIAN.indexOf(ch);
    return p >= 0 ? String(p) : ch;
  });
}
